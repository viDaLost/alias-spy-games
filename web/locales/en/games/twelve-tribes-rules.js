// «Двенадцать колен» — правила, колода и соперники. Без разметки.
//
// Это библейская родня UNO, и родство тут не в названии, а в устройстве: у
// каждой карты два свойства, и ход разрешён, если хоть одно совпало с верхней
// картой сброса. У UNO это цвет и число; здесь — стан и жребий.
//
// Почему станы. В книге Чисел (гл. 2) Израиль в пустыне стоит не толпой, а
// четырьмя станами вокруг скинии: Иуда на востоке, Рувим на юге, Ефрем на
// западе, Дан на севере, по три колена в каждом. Четыре стана — это ровно
// четыре масти, и они не выдуманы под игру: так написано.
//
// Файл нарочно не знает ни одного слова про экран. Причина простая: правила
// карточной игры ломаются тихо — колода незаметно теряет карту, «Плен» уходит
// в ход, когда не должен, раздача не кончается вовсе. Увидеть это на экране
// нельзя, а прогнать десять тысяч раздач машиной — можно, и проверка
// scripts/check-twelve-tribes.mjs именно это и делает, загружая этот файл в
// узел без всякого браузера.

(function () {
  'use strict';

  /*
    Четыре стана — четыре масти. Сторона света и колена взяты из Чисел 2:3–31;
    знак стана (лев, человек, телец, орёл) — предание, а не Писание, и в
    правилах игры он назван знаком, а не цитатой.
  */
  const CAMPS = [
    {
      id: 'judah', name: 'Judah', side: 'восток', sign: 'lion',
      tribes: ['Judah', 'Иссахар', 'Завулон'],
    },
    {
      id: 'reuben', name: 'Рувим', side: 'юг', sign: 'человек',
      tribes: ['Рувим', 'Simeon', 'Гад'],
    },
    {
      id: 'ephraim', name: 'Ефрем', side: 'запад', sign: 'bull',
      tribes: ['Ефрем', 'Manasseh', 'Вениамин'],
    },
    {
      id: 'dan', name: 'Дан', side: 'север', sign: 'eagle',
      tribes: ['Дан', 'Асир', 'Неффалим'],
    },
  ];
  const CAMP_IDS = CAMPS.map((camp) => camp.id);
  const campOf = (id) => CAMPS.find((camp) => camp.id === id) || null;

  /*
    Пять особых карт. Каждая названа тем, что она делает, а не тем, на что
    похожа: «Суббота» — это покой, и сосед действительно отдыхает; «Иордан»
    обращается назад (Пс. 113:3), и ход идёт в другую сторону.

    Цена в очках — это цена сброшенной карты, а не оставшейся на руке. Цифра
    стоит своей цифрой, любое действие — тройку. Считается она сразу, тем же
    ходом, каким карта легла на стол: счёт растёт на глазах, и видно, за что.

    Почему не как в родительской игре, где очки снимают с рук проигравших:
    там счёт появляется раз в раздачу и целиком зависит от того, кто вышел
    первым. Здесь он зависит от того, сколько ты сыграл, — а это ровно то,
    чем игрок и занят.
  */
  const ACTION_SCORE = 3;
  const KINDS = {
    number: { title: 'Lot', wild: false, draw: 0,
      note: 'Кладётся на свой стан или на такой же жребий. В счёт идёт своей цифрой.' },
    sabbath: { title: 'Sabbath', wild: false, draw: 0,
      note: 'Сосед покоится — ход мимо него. В счёт: +3.' },
    jordan: { title: 'Jordan', wild: false, draw: 0,
      note: 'Иордан обратился назад: ход меняет сторону. В счёт: +3.' },
    journey: { title: 'Странствие', wild: false, draw: 2,
      note: 'Сосед берёт две — или переводит их дальше своим «Странствием». В счёт: +3.' },
    lot: { title: 'Жребий колен', wild: true, draw: 0,
      note: 'Кладётся на что угодно: вы называете стан. В счёт: +3.' },
    exile: { title: 'Captivity', wild: true, draw: 4,
      note: 'Вы называете стан, сосед берёт четыре — или переводит их дальше своим «Пленом». В счёт: +3.' },
  };

  /*
    Сколько карт карта выдаёт соседу — свойство карты, а не знание движка.

    Раньше двойку странствия и четвёрку плена знал движок, а на экране их не
    было вовсе: игрок узнавал цену карты, только сыграв её. Теперь число живёт
    в одном месте — отсюда его берёт и движок, и надпись на самой карте.
  */
  const drawsOf = (card) => KINDS[card.kind].draw || 0;

  /** Сколько очков приносит сброшенная карта: цифра — себя, действие — тройку. */
  const scoreOf = (card) => (card.kind === 'number' ? card.rank : ACTION_SCORE);

  /*
    Состав колоды — сто восемь карт, как в родительской игре, и по той же
    причине: при семи картах на руке и четырёх игроках колода из ста восьми
    переживает раздачу без перетасовки сброса в среднем, но не всегда, — а
    значит перетасовка обязана работать, и проверка это спрашивает.

      4 стана × (0 один раз, 1–9 по два)            = 76
      4 стана × (суббота, иордан, странствие по два) = 24
      жребий ×4 и плен ×4                            =  8
  */
  function buildDeck() {
    const deck = [];
    let serial = 0;
    const put = (camp, kind, rank) => {
      deck.push({ id: `c${serial += 1}`, camp, kind, rank: rank ?? null });
    };
    for (const camp of CAMP_IDS) {
      put(camp, 'number', 0);
      for (let rank = 1; rank <= 9; rank += 1) { put(camp, 'number', rank); put(camp, 'number', rank); }
      for (const kind of ['sabbath', 'jordan', 'journey']) { put(camp, kind); put(camp, kind); }
    }
    for (let i = 0; i < 4; i += 1) { put(null, 'lot'); put(null, 'exile'); }
    return deck;
  }

  /*
    Тасовка Фишера — Йетса на переданном источнике случайности. Источник
    передаётся, а не берётся из Math.random, ровно ради проверки: десять тысяч
    раздач должны повторяться от запуска к запуску, иначе упавшая проверка
    ничего не докажет — её нельзя будет воспроизвести.
  */
  function shuffle(list, random) {
    for (let i = list.length - 1; i > 0; i -= 1) {
      const j = Math.floor(random() * (i + 1));
      [list[i], list[j]] = [list[j], list[i]];
    }
    return list;
  }

  /*
    Ход разрешён, если совпало хоть что-нибудь: стан, жребий или сам род карты.

    Последнее — не мелочь: «Суббота» кладётся на «Субботу» любого стана, и без
    этого правила особые карты застревали бы на руках до конца раздачи.

    У «Плена» условие строже, и оно то же, что в родительской игре: его кладут,
    только когда в руке нет ни одной карты нынешнего стана. Иначе эта карта
    превращается в «выиграть, ничего не решая»: четыре карты соседу и свой стан
    по желанию — в любой миг партии.
  */
  function playable(state, card, hand) {
    /*
      Штраф на столе — особое положение, и правила в нём другие.

      Когда сосед подкинул «Странствие» или «Плен», взять карты можно не
      сразу: у того, кому их подкинули, есть право перевести долг дальше — но
      только такой же картой. «Странствие» кроется «Странствием», «Плен» —
      «Пленом»; накопленное складывается и уходит следующему, а тот волен
      перевести его ещё дальше.

      Запрет на «Плен» при своём стане здесь не действует: он придуман затем,
      чтобы «Плен» не бросали от хорошей жизни, а тут его кладут от беды —
      иначе придётся брать всё, что накопилось.
    */
    if (state.penalty) return card.kind === state.penalty.kind;
    if (card.kind === 'exile') {
      return !hand.some((one) => one.camp === state.camp);
    }
    if (KINDS[card.kind].wild) return true;
    if (card.camp === state.camp) return true;
    const top = state.pile[state.pile.length - 1];
    if (!top) return true;
    if (card.kind === 'number' && top.kind === 'number') return card.rank === top.rank;
    return card.kind === top.kind;
  }

  /** Какими картами с руки можно пойти прямо сейчас: список мест в руке. */
  function legalMoves(state, seat) {
    const hand = state.players[seat].hand;
    const out = [];
    for (let i = 0; i < hand.length; i += 1) if (playable(state, hand[i], hand)) out.push(i);
    return out;
  }

  window.TwelveTribesRules = {
    CAMPS, CAMP_IDS, KINDS, ACTION_SCORE, campOf, scoreOf, drawsOf, buildDeck, shuffle, playable, legalMoves,
    HAND: 7,
    // Сколько человек садится за стол. Восемь — предел колоды: по семь карт на
    // руки это 56 карт из 108, и на игру остаётся ровно половина.
    SEATS_MAX: 8,
  };
}());
