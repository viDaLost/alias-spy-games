import fs from 'node:fs';
import {readTranslations} from './i18n-utils.mjs';
import { CATALOG } from '../cloudflare/bible-sketch-worker/src/catalog.js';
import { LOCATIONS } from '../cloudflare/spy-worker/src/locations.js';
// Generated from the same translations as the clients; protocol IDs never change.
export function buildGameTranslations(root) {
  const dictionaries=readTranslations(root);
  const phrases=[...new Set([...LOCATIONS,...Object.values(CATALOG).flat().map(word=>word.label)])];
  const output={};
  for(const phrase of phrases) {
    output[phrase]=['en','de','es'].map(lang=>{
      if(!dictionaries[lang][phrase])throw new Error(`Missing ${lang} online word: ${phrase}`);
      return dictionaries[lang][phrase];
    });
  }
  return '// Generated by scripts/build-game-translations.mjs.\nexport const gameTranslations = '+JSON.stringify(output)+';\n';
}
if(process.argv[1]===import.meta.filename){fs.mkdirSync('cloudflare/shared',{recursive:true});fs.writeFileSync('cloudflare/shared/game-translations.js',buildGameTranslations(process.cwd()));}
