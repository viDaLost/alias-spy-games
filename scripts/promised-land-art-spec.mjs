// Рабочие размеры картинок «Земли обетованной» — в одном месте.
//
// Их знают двое: перегонщик PNG→WebP и проверка. Держи их врозь — и однажды
// перегон уменьшит картинку сильнее, чем проверка готова стерпеть, либо
// наоборот: проверка пропустит миниатюру. Ошибка тихая, вылезет на чужом
// телефоне мыльной иллюстрацией.
//
// Размеры взяты от того, как картинка показывается, с запасом вдвое на экраны
// удвоенной плотности: иллюстрация удела живёт в середине кольца шириной от
// силы 330 точек, значок строения — десяток точек, иконка меню у всех игр
// проекта 224.

export const TARGETS = {
  plots: { size: 768, quality: 0.82 },
  cards: { size: 768, quality: 0.82 },
  icons: { size: 256, quality: 0.86 },
  build: { size: 256, quality: 0.86 },
  tokens: { size: 256, quality: 0.86 },
  menu: { size: 224, quality: 0.88 },
  scene: { size: 1536, quality: 0.82 },
  showcase: { size: 1024, quality: 0.84 },
};

/*
  Запас вниз: браузер округляет сторону при сжатии пропорций, да и перерисовать
  набор в чуть меньшем размере — не беда. А вот вдвое меньше ожидаемого — уже
  миниатюра, и это ловится.
*/
export const TOLERANCE = 0.85;
export const minSide = (key) => Math.round(TARGETS[key].size * TOLERANCE);
