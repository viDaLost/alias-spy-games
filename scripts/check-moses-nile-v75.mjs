import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright-core';

const root = process.cwd();
const gameRoot = path.join(root, 'web/games/moses-nile-v7');
const index = fs.readFileSync(path.join(gameRoot, 'index.html'), 'utf8');
const game = fs.readFileSync(path.join(gameRoot, 'js/game-v75.js'), 'utf8');
const assets = fs.readFileSync(path.join(gameRoot, 'js/assets.js'), 'utf8');
const shaders = fs.readFileSync(path.join(gameRoot, 'js/shaders.js'), 'utf8');
const effects = fs.readFileSync(path.join(gameRoot, 'js/fx.js'), 'utf8');
const materials = fs.readFileSync(path.join(gameRoot, 'js/materials.js'), 'utf8');
const runtimeFiles = fs.readdirSync(path.join(gameRoot, 'js')).filter((name) => name.endsWith('.js')).sort();
const deployWorkflow = fs.readFileSync(path.join(root, '.github/workflows/deploy-moses-nile-v740-preview.yml'), 'utf8');
const modelManifest = JSON.parse(fs.readFileSync(path.join(root, 'scripts/data/moses-nile-model-manifest.json'), 'utf8'));

for (const token of [
  'V7.5.1 · LOADING',
  'game-v75.js?v=752',
  'fallback-canvas',
  'aria-label="Двигаться влево"',
  'js/shaders.js',
  'js/fx.js',
  'js/materials.js',
  'id="btn-jump"',
  'id="btn-dive"',
  'id="hearts"',
  'id="pause-screen"',
  'id="scene-bg"',
  '--sky-horizon',
]) {
  if (!index.includes(token)) throw new Error(`V7.5.1 index is missing ${token}`);
}
if (index.includes('type="module"') || index.includes('v740-visual-overhaul.js') || index.includes('v7310-mobile-polish.js')) {
  throw new Error('V7.5.1 must not load the legacy multi-runtime patch stack');
}
// Небо теперь процедурное: фотографической подложки в игре быть не должно.
if (index.includes('nile-reference-bg-v75.webp') || fs.existsSync(path.join(gameRoot, 'assets/nile-reference-bg-v75.webp'))) {
  throw new Error('The reference photo background must be gone — the sky is generated by a shader now');
}
for (const token of [
  '__mosesV75ReferenceRebuild',
  'oneRenderLoop: true',
  'activateFallback',
  'V75DistantPyramid',
  'V751PapyrusBank',
  'V75ClosedBasketLid',
  'waterNormal.offset',
  'waterDetailNormal.offset',
  'V751DetailedCrocodileModel',
  "cloneModel?.('lotus'",
  'buildBanks();',
  'function jump()',
  'function dive()',
  'V751PapyrusGate',
  'V751Whirlpool',
  'V751NileHippo',
  'MESH_RANGE',
  'mergeByMaterial',
  'V751SandstormSky',
  'V751HorizonDunes',
  'SCROLL_TILE',
  'scrollLayers',
  'emitSwipeWave',
  'buildDunes();',
  'proceduralSkyVisible: true',
  "const LANES = [-3.75, 0, 3.75]",
]) {
  if (!game.includes(token)) throw new Error(`V7.5.1 engine is missing ${token}`);
}
if (game.includes('OctahedronGeometry')) throw new Error('The placeholder octahedron power-up is still present');
for (const token of ['preloadGameplayModels', 'models/v73/crocodile.glb', 'models/v73/lotus-flower.obj']) {
  if (!assets.includes(token)) throw new Error(`V7.5.1 asset manager is missing ${token}`);
}
for (const token of ['createRiverMaterial', 'createSkyMaterial', 'createDustSheetMaterial', 'applyCrocodileSwim', 'createShieldMaterial', 'createParticleMaterial', 'applyWind', 'window.NileShaders']) {
  if (!shaders.includes(token)) throw new Error(`The Nile shader library is missing ${token}`);
}

// Процедурный PBR и освещение небом: без них модели без UV-развёртки
// оставались плоской заливкой, из-за которой сцена выглядела пластмассовой.
for (const token of [
  'window.NileMaterials',
  'buildLightProbe',
  'SphericalHarmonics3',
  'addSkyReflection',
  'applyBoxUV',
  'roughnessMap',
  'normalMap',
]) {
  if (!materials.includes(token)) throw new Error(`The Nile material library is missing ${token}`);
}
// Библиотеки — без собственного кадрового цикла: слои V7.3.x однажды уже
// подрались за один экран, и возвращать многослойность нельзя.
for (const [name, source] of [['materials.js', materials], ['shaders.js', shaders], ['fx.js', effects]]) {
  if (/setAnimationLoop/.test(source)) throw new Error(`${name} must stay a library without its own render loop`);
}
const expectedRuntime = ['assets.js', 'fx.js', 'game-v75.js', 'materials.js', 'shaders.js', 'sound.js'];
if (runtimeFiles.join(',') !== expectedRuntime.join(',')) {
  throw new Error(`Unexpected runtime files: ${runtimeFiles.join(', ')}`);
}
// Людей с берегов убрали намеренно: проверка держит это состояние, чтобы
// скелетная модель и её анимация не вернулись вместе с чужой правкой.
for (const token of ['V751RiverFolk', 'buildBankPeople', 'animateFolk', 'cloneRigged', 'human.glb']) {
  if (game.includes(token) || assets.includes(token)) {
    throw new Error(`The bank people were removed on request but ${token} is back`);
  }
}
// Пирамиды: ступенчатая кладка и известняковая облицовка вместо плоских
// самосветящихся конусов, которые читались как бумажные треугольники.
for (const token of [
  'stepPyramidGeometry', 'V75DistantPyramid', 'V751NileHippo', 'duneHeight', 'contactShadowTexture',
  // Дно Нила из настоящих фотограмметрических карт и собранный вручную
  // папирус вместо широколистного Plant_2 у самой воды.
  'V751NileBed', 'papyrusClumpParts', 'V751BankBroadleaf',
  'textures/terrain/pebbles-color.jpg',
  // Рельеф песка едет вместе с растительностью, иначе деревья идут сквозь
  // барханы; камень русла — на настоящей фотограмметрии.
  'applyDuneRelief', 'uDuneScroll', 'riverStoneMaterial', 'textures/terrain/rock-color.jpg',
]) {
  if (!game.includes(token)) throw new Error(`The Nile scene is missing ${token}`);
}
/*
  Фаза течения копится, а не считается как время × скорость: множитель
  сдвигал всю картину воды при каждом изменении скорости, и на сбросе
  ускорения пена прыгала назад. Проверка держит это состояние.
*/
if (!shaders.includes('float t = uPhase;') || shaders.includes('float t = uTime * uFlow;')) {
  throw new Error('The river shader must read an accumulated flow phase, not uTime * uFlow');
}
if (!game.includes('state.flowPhase += state.flowRate * dt')) {
  throw new Error('The engine must accumulate the river flow phase on the CPU');
}
for (const token of ['window.NileFX', 'splash(', 'ripple(', 'shake(']) {
  if (!effects.includes(token)) throw new Error(`The Nile effects system is missing ${token}`);
}
for (const token of [
  'ASSET_PACKAGE_REV=8887faf7638a4168d37583f17b1c8eec9c46dd3f',
  'downloads/moses-nile-v737-full.zip',
  'ASSET_PACKAGE_SHA256=06fd34662ba8424a9987f74f5c9592479ef3ec25a77a7f1b53dd36c4ed0d99e5',
  'models/v73/crocodile.glb',
  'textures/damp-sand-normal-gl-1k.jpg',
  'textures/ganges-pebbles-normal-gl-1k.jpg',
  'if (vertices !== 957 || faces !== 1260)',
]) {
  if (!deployWorkflow.includes(token)) throw new Error(`V7.5.1 deploy is missing verified package wiring: ${token}`);
}
if (modelManifest.delivery !== 'same-origin-build-extraction' || modelManifest.package?.sha256 !== '06fd34662ba8424a9987f74f5c9592479ef3ec25a77a7f1b53dd36c4ed0d99e5') {
  throw new Error('The real-model package manifest is not pinned to the verified repository archive');
}
if (process.env.MOSES_STATIC_ONLY === '1') {
  console.log('OK: Moses Nile V7.5.1 static contract, pinned repository 3D package, PBR normal maps and procedural sandstorm sky are valid.');
  process.exit(0);
}

const mime = new Map([
  ['.html', 'text/html; charset=utf-8'],
  ['.js', 'text/javascript; charset=utf-8'],
  ['.webp', 'image/webp'],
  ['.jpg', 'image/jpeg'],
  ['.glb', 'model/gltf-binary'],
  ['.obj', 'text/plain; charset=utf-8'],
]);
const server = http.createServer((request, response) => {
  const url = new URL(request.url || '/', 'http://127.0.0.1');
  const relative = decodeURIComponent(url.pathname === '/' ? '/index.html' : url.pathname);
  const target = path.resolve(gameRoot, `.${relative}`);
  if (!target.startsWith(`${gameRoot}${path.sep}`) || !fs.existsSync(target) || !fs.statSync(target).isFile()) {
    response.writeHead(404).end('Not found');
    return;
  }
  response.writeHead(200, { 'Content-Type': mime.get(path.extname(target)) || 'application/octet-stream', 'Cache-Control': 'no-store' });
  fs.createReadStream(target).pipe(response);
});

await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
const url = `http://127.0.0.1:${server.address().port}/`;
const browser = await chromium.launch({
  headless: true,
  executablePath: process.env.CHROME_BIN || '/usr/bin/google-chrome',
  args: ['--no-sandbox', '--disable-dev-shm-usage', '--disable-webgl'],
});
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const page = await context.newPage();
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
await page.route('**/vendor/**', (route) => route.fulfill({ status: 200, contentType: 'text/javascript', body: '' }));
await page.route('**/js/assets.js*', (route) => route.fulfill({
  status: 200,
  contentType: 'text/javascript',
  body: 'window.assetManager={};',
}));
await page.route('**/js/sound.js*', (route) => route.fulfill({
  status: 200,
  contentType: 'text/javascript',
  body: 'window.gameAudio={init(){},playSplash(){},playCollect(){},playPowerup(){},playHit(){}};',
}));

try {
  await page.goto(url, { waitUntil: 'networkidle', timeout: 20_000 });
  await page.waitForFunction(() => window.__mosesV75Mode === 'fallback', null, { timeout: 5_000 });
  const initial = await page.evaluate(async () => {
    const bg = getComputedStyle(document.getElementById('scene-bg')).backgroundImage;
    const left = document.getElementById('btn-left').getBoundingClientRect();
    const right = document.getElementById('btn-right').getBoundingClientRect();
    return {
      mode: window.__mosesV75Mode,
      fallbackClass: document.body.classList.contains('fallback-mode'),
      background: bg,
      controlsInsideViewport: left.left >= 0 && right.right <= innerWidth && left.bottom <= innerHeight && right.bottom <= innerHeight,
      badge: document.getElementById('version-badge').textContent,
    };
  });
  if (initial.mode !== 'fallback' || !initial.fallbackClass) throw new Error(`Fallback did not initialize: ${JSON.stringify(initial)}`);
  if (!initial.background.includes('gradient')) throw new Error(`The procedural sky gradient is not applied: ${initial.background}`);
  if (!initial.controlsInsideViewport) throw new Error('Mobile controls are clipped');
  if (!initial.badge.startsWith('V7.5.1 · LITE READY')) throw new Error(`Unexpected fallback badge: ${initial.badge}`);

  await page.locator('#start-btn').click();
  await page.waitForFunction(() => Number(document.getElementById('dist-txt')?.textContent || 0) >= 8, null, { timeout: 3_000 });
  await page.keyboard.press('ArrowRight');
  await page.waitForTimeout(220);
  await page.keyboard.press('ArrowUp');
  await page.waitForTimeout(140);
  const airborne = await page.evaluate(() => ({ y: window.__mosesV75State?.y ?? 0, air: !!window.__mosesV75State?.airborne }));
  if (!airborne.air || airborne.y <= 0) throw new Error(`The wave jump does not lift the basket: ${JSON.stringify(airborne)}`);
  await page.waitForTimeout(700);
  await page.keyboard.press('ArrowDown');
  await page.waitForTimeout(140);
  const diving = await page.evaluate(() => ({ y: window.__mosesV75State?.y ?? 0, dive: window.__mosesV75State?.dive ?? 0 }));
  if (diving.dive <= 0 || diving.y >= 0) throw new Error(`The dive does not submerge the basket: ${JSON.stringify(diving)}`);
  await page.waitForTimeout(350);
  const running = await page.evaluate(() => {
    const canvas = document.getElementById('fallback-canvas');
    const ctx = canvas.getContext('2d');
    const sample = ctx.getImageData(Math.floor(canvas.width * .30), Math.floor(canvas.height * .45), Math.max(1, Math.floor(canvas.width * .40)), Math.max(1, Math.floor(canvas.height * .45))).data;
    let painted = 0;
    for (let i = 3; i < sample.length; i += 4) if (sample[i] > 0) painted += 1;
    return {
      playing: document.body.classList.contains('is-playing'),
      startHidden: document.getElementById('start-screen').classList.contains('hidden'),
      distance: Number(document.getElementById('dist-txt').textContent || 0),
      hearts: document.querySelectorAll('#hearts span').length,
      painted,
    };
  });
  if (!running.playing || !running.startHidden || running.distance < 8 || running.painted < 200) throw new Error(`Fallback gameplay is not visibly running: ${JSON.stringify(running)}`);
  if (running.hearts !== 3) throw new Error(`The run should start with three hearts, got ${running.hearts}`);
  if (errors.length) throw new Error(`Fallback page errors: ${errors.join(' | ')}`);
  console.log('OK: Moses Nile V7.5.1 uses local 3D models, a procedural sandstorm sky, GLSL water/wind shaders and lane+jump+dive gameplay, plus an unclipped playable no-WebGL fallback.');
} finally {
  await context.close();
  await browser.close();
  await new Promise((resolve) => server.close(resolve));
}
