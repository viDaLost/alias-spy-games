// Reproducible raster tile export: a single painting, shared borders, exact alignment.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
globalThis.window = {};
require('../web/games/kingdoms-rules.js');
const R = window.KingdomsRules;
const out = 'web/assets/kingdoms/map-v3';
fs.mkdirSync(out, {recursive:true});
process.env.MAGICK_THREAD_LIMIT = '1';
const scratch=fs.mkdtempSync(path.join(os.tmpdir(),'kingdoms-map-'));
const sites=R.AREAS.map(a=>{
 const i=R.REGION_IDS.indexOf(a.region),angle=(-90+i*60)*Math.PI/180;
 const rx=Math.cos(angle),ry=Math.sin(angle),tx=-ry,ty=rx;
 let x=450+rx*300,y=470+ry*300;
 if(a.role==='rim'){x+=rx*96;y+=ry*96;}
 if(a.role==='hub'){x-=rx*62;y-=ry*62;}
 if(a.role==='cw'){x+=tx*90;y+=ty*90;}
 if(a.role==='ccw'){x-=tx*90;y-=ty*90;}
 return {id:a.id,x,y};
});
function clip(poly,nx,ny,d){
 const out=[];
 for(let i=0;i<poly.length;i++){
  const a=poly[i],b=poly[(i+1)%poly.length];
  const va=a[0]*nx+a[1]*ny-d,vb=b[0]*nx+b[1]*ny-d;
  if(va<=1e-7)out.push(a);
  if((va<0&&vb>0)||(va>0&&vb<0)){const t=va/(va-vb);out.push([a[0]+t*(b[0]-a[0]),a[1]+t*(b[1]-a[1])]);}
 }return out;
}
const round=n=>Math.round(n*100)/100;
function border(a,b){
 // The same endpoints always produce exactly the same curved border in both cells.
 const reverse=a[0]>b[0]||(a[0]===b[0]&&a[1]>b[1]);
 const [u,v]=reverse?[b,a]:[a,b];const dx=v[0]-u[0],dy=v[1]-u[1],len=Math.hypot(dx,dy);
 const outer=(u[0]===v[0]&&(u[0]===0||u[0]===900))||(u[1]===v[1]&&(u[1]===0||u[1]===940));
 const amp=outer?0:Math.min(10,len*.055);const points=[];
 for(let i=0;i<=6;i++){const t=i/6;const offset=Math.sin(t*Math.PI*2)*amp;points.push([round(u[0]+dx*t-dy/len*offset),round(u[1]+dy*t+dx/len*offset)]);}
 return reverse?points.reverse():points;
}
execFileSync('convert',['docs/kingdoms-map/source.webp','-resize','1800x1880!',path.join(scratch,'master.png')]);
execFileSync('convert',[path.join(scratch,'master.png'),'-quality','88',`${out}/base.webp`]);
const tiles={};
for(const s of sites){
 let p=[[0,0],[900,0],[900,940],[0,940]];
 for(const q of sites){if(q===s)continue;p=clip(p,q.x-s.x,q.y-s.y,(q.x*q.x+q.y*q.y-s.x*s.x-s.y*s.y)/2);}
 p=p.map(v=>v.map(round)).filter((v,i,all)=>i===0||Math.hypot(v[0]-all[i-1][0],v[1]-all[i-1][1])>.01);
 if(Math.hypot(p[0][0]-p.at(-1)[0],p[0][1]-p.at(-1)[1])<=.01)p.pop();
 const points=p.flatMap((v,i)=>border(v,p[(i+1)%p.length]).slice(0,-1));
 const x=Math.floor(Math.min(...points.map(v=>v[0]))),y=Math.floor(Math.min(...points.map(v=>v[1])));
 const w=Math.ceil(Math.max(...points.map(v=>v[0])))-x,h=Math.ceil(Math.max(...points.map(v=>v[1])))-y;
 const file=`${out}/${s.id}.webp`;
 execFileSync('convert',[path.join(scratch,'master.png'),'(','-size','1800x1880','xc:black','-fill','white','-draw','polygon '+points.map(v=>v.map(n=>n*2).join(',')).join(' '),'-alpha','off',')','-compose','CopyOpacity','-composite','-crop',`${w*2}x${h*2}+${x*2}+${y*2}`,'+repage','-quality','90',file]);
 tiles[s.id]={file,x,y,w,h,points};
}
fs.writeFileSync('web/games/kingdoms-map.js',`// Generated by scripts/build-kingdoms-map.mjs. Shared geometry for art and hit testing.\n(function(root){ root.KingdomsMap = ${JSON.stringify({width:900,height:940,base:`${out}/base.webp`,tiles})}; })(typeof window !== 'undefined' ? window : globalThis);\n`);
fs.rmSync(scratch,{recursive:true,force:true});
console.log('Exported base + 24 aligned transparent WebP territories.');
