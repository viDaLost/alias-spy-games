export const FALLBACK_CODE = { expense: 'other', income: 'other_in' };

const DEFAULT_BY_CODE = Object.fromEntries(DEFAULT_CATEGORIES.map((c) => [c.code, c]));

export const norm = (s) => String(s || '').toLowerCase().replace(/ё/g, 'е');

export function wordsOf(text) {
  return norm(text).split(/[^a-zа-я0-9/]+/i).filter(Boolean);
}

// Основа слова для выученных ключевых слов: «шаурму» и «шаурма» → «шаур».
export function stemWord(w) {
  w = norm(w);
  if (w.length <= 4) return w;
  if (w.length <= 6) return w.slice(0, w.length - 1);
  return w.slice(0, w.length - 2);
}

function matchesStem(words, padded, stem) {
  // «слово » с пробелом в конце — только точное совпадение слова или фразы.
  if (stem.endsWith(' ')) {
    const t = stem.trim();
    return t.includes(' ') ? padded.includes(' ' + t + ' ') : words.includes(t);
  }
  if (stem.includes(' ')) return padded.includes(' ' + stem);
  return words.some((w) => w.startsWith(stem));
}

export function hasIncomeHint(text) {
  const words = wordsOf(text);
  const padded = ' ' + words.join(' ') + ' ';
  return INCOME_HINTS.some((s) => matchesStem(words, padded, s));
}

/**
 * Подбирает категорию пользователя по тексту.
 * cats — активные категории пользователя ({ id, kind, code, name, keywords, parent_id }).
 * Возвращает категорию или null. Выученные слова важнее стандартного словаря,
 * подкатегория («Аптека») важнее своей категории («Здоровье»).
 */
export function guessCategory(text, cats, kind) {
  const words = wordsOf(text);
  if (!words.length) return null;
  const padded = ' ' + words.join(' ') + ' ';
  const ofKind = cats.filter((c) => c.kind === kind);
  const pool = [...ofKind.filter((c) => c.parent_id), ...ofKind.filter((c) => !c.parent_id)];

  // 1. Слова, которым пользователь научил бота.
  for (const c of pool) {
    const kws = String(c.keywords || '').split(',').map((s) => s.trim()).filter(Boolean);
    if (kws.some((k) => matchesStem(words, padded, k))) return c;
  }
  // 2. Название категории в тексте («подарки», «такси»).
  for (const c of pool) {
    const nameStems = wordsOf(c.name).filter((w) => w.length >= 4).map(stemWord);
    if (nameStems.some((st) => words.some((w) => w.startsWith(st)))) return c;
  }
  // 3. Стандартный словарь.
  let best = null, bestLen = 0;
  for (const c of pool) {
    const def = DEFAULT_BY_CODE[c.code];
    if (!def) continue;
    for (const s of def.words) {
      if (s.length > bestLen && matchesStem(words, padded, s)) { best = c; bestLen = s.length; }
    }
  }
  return best;
}

export function fallbackCategory(cats, kind) {
  const pool = cats.filter((c) => c.kind === kind && !c.parent_id);
  return pool.find((c) => c.code === FALLBACK_CODE[kind]) || pool[pool.length - 1] || null;
}

// Слово из описания, которое стоит запомнить для категории (первое «содержательное»).
const STOP = new Set(['на', 'за', 'в', 'во', 'по', 'и', 'с', 'со', 'для', 'от', 'до', 'из', 'к', 'у', 'это', 'мне', 'себе', 'новый', 'новая', 'новые', 'один', 'одна', 'еще', 'ещё', 'всякое', 'разное', 'всего']);

export function learnableWord(note) {
  const w = String(note || '').split(/[^\p{L}\p{N}]+/u).find((x) => {
    const n = norm(x);
    return n.length >= 3 && !STOP.has(n) && !/^\d/.test(n);
  });
  return w ? { word: w.toLowerCase(), stem: stemWord(w) } : null;
}

// Эмодзи в начале строки («🧸 Дети» → ['🧸', 'Дети']).
export function splitEmoji(s) {
  s = String(s || '').trim();
  const m = s.match(/^([\p{Extended_Pictographic}\p{Emoji_Presentation}][\u{FE0F}\u{200D}\p{Extended_Pictographic}\p{Emoji_Modifier}]*)\s*(.*)$/u);
  return m ? [m[1], m[2].trim()] : ['', s];
}
