// тем живут в браузере. В воркере window нет, а eval запрещён — значит, обычный
// приём из проверок (new Function с подставленным window) здесь не годится.
//
// Поэтому window подставляется по-настоящему: сборщик выполняет те же файлы,
// что отдаются браузеру, и они находят window на своём месте. Ни строчки правил
// при этом не переписано.

