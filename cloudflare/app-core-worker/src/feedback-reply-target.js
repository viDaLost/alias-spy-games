// Чей это был отзыв — по сообщению, на которое ответили свайпом.
//
// Вынесено отдельным файлом, потому что это решает, кому уйдёт ответ от имени
// приложения, а сам воркер целиком в обычном Node не запускается: ниже по
// цепочке есть импорты cloudflare:. Здесь их нет, и проверка гоняет ровно тот
// код, который работает в бою, а не его пересказ.
//
// Ответ засчитывается, только если выполнены все условия сразу:
//
//   * отвечают на сообщение бота. Своё собственное письмо переслать себе может
//     кто угодно, и без этого ответ ушёл бы по чужой метке;
//   * это именно отзыв, а не обращение в поддержку: у поддержки свой разбор
//     ниже по цепочке, и перехватывать её сообщения нельзя;
//   * метка на месте и в ней настоящий Telegram ID.

const TARGET_RE = /ID отзыва:\s*fb_(\d{5,20})\b/i;

export function feedbackReplyTarget(reply) {
  if (!reply || reply.from?.is_bot !== true) return '';
  const body = String(reply.text || reply.caption || '');
  if (!/отзыв о приложении/i.test(body)) return '';
  const id = String(body.match(TARGET_RE)?.[1] || '');
  return /^\d{5,20}$/.test(id) ? id : '';
}
