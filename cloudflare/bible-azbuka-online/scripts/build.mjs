import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
const root=resolve(import.meta.dirname,'..');
const html=readFileSync(resolve(root,'index.html'),'utf8');
const source=readFileSync(resolve(root,'worker.template.mjs'),'utf8');
const mark="'__BIBLE_AZBUKA_HTML__'";
if(!source.includes(mark))throw Error('Missing html placeholder');
mkdirSync(resolve(root,'dist'),{recursive:true});
const result=source.replace(mark,JSON.stringify(html));
writeFileSync(resolve(root,'dist/worker.mjs'),result);
console.log('Built bible-azbuka Worker:',result.length,'bytes');
